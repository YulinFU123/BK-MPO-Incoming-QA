  function validate(value) {
    const invalid = () => {
      throw Error('引导进度无效，请检查或恢复配置。');
    };
    if (
      !value ||
      typeof value !== 'object' ||
      Array.isArray(value) ||
      Object.keys(value).some((k) => !['version', 'progress'].includes(k)) ||
      value.version !== 1 ||
      !value.progress ||
      typeof value.progress !== 'object' ||
      Array.isArray(value.progress)
    )
      invalid();
    for (const [id, row] of Object.entries(value.progress)) {
      const guide = get(id);
      if (
        !guide ||
        !row ||
        typeof row !== 'object' ||
        Array.isArray(row) ||
        Object.keys(row).sort().join() !== 'status,step' ||
        !['paused', 'completed', 'skipped'].includes(row.status) ||
        !Number.isInteger(row.step) ||
        row.step < 0 ||
        row.step >= guide.steps.length
      )
        invalid();
    }
    return structuredClone(value);
  }
