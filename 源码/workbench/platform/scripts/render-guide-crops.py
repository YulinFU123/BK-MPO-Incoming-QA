"""Regenerate local detail thumbnails from curated, bundled screenshots. No desktop capture.
Usage: python scripts/render-guide-crops.py --node <node or bundled Electron.exe> (Pillow required).
The manifest's rectangles always refer to the unmodified original, never to a live workspace.
"""
import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'desktop' / 'app'
DEST = APP / 'assets' / 'guide-focus'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--node', default='node')
    node = ap.parse_args().node
    js = "const m=require('./desktop/app/guide-pictures'),g=require('./domain/guides');process.stdout.write(JSON.stringify(g.all.flatMap(r=>r.steps.map((_,i)=>[r.id,i,m.get(r.id,i)]))))"
    rows = json.loads(subprocess.check_output([node, '-e', js], cwd=ROOT, env=dict(os.environ, ELECTRON_RUN_AS_NODE='1')).decode('utf-8'))
    out, used = {}, set()
    DEST.mkdir(parents=True, exist_ok=True)
    for gid, step, pic in rows:
        if not pic:
            raise ValueError(f'missing or invalid illustration: {gid}:{step}')
        if pic['kind'] != 'capture' or not pic['file'].endswith('.png'):
            continue
        with Image.open(APP / pic['file']) as im:
            w, h = im.size
            x, y, rw, rh = [v / 100 * dim for v, dim in zip(pic['rect'], (w, h, w, h))]
            if gid == 'workspace-manager' and step == 1 and pic['file'].endswith('/workspace-create.png'):
                # Existing hand-cropped detail from the same 468x602 example dialog.
                box, url = (25, 274, 442, 495), 'assets/guide-previews/workspace-source.png'
            else:
                # Keep neighbouring labels and some context, without reducing a small
                # checkbox on a 1300px-wide window to an illegible dot at 125% zoom.
                bw = min(w, max(432, math.ceil(rw * 1.52 + 64)))
                bh = min(h, max(185, math.ceil(rh * 1.55 + 56)))
                bw = min(w, max(bw, round(bh * 1.55)))
                bh = min(h, max(bh, round(bw / 2.8)))
                if bw * bh >= w * h * .82 or (w <= 640 and h <= 310):
                    continue
                left = min(max(0, round(x + rw / 2 - bw / 2)), w - bw)
                top = min(max(0, round(y + rh / 2 - bh / 2)), h - bh)
                box = (left, top, left + bw, top + bh)
                name = 'cut-' + hashlib.sha256((pic['file'] + str(box)).encode()).hexdigest()[:16] + '.png'
                if name not in used:
                    im.crop(box).save(DEST / name, optimize=True)
                    used.add(name)
                url = 'assets/guide-focus/' + name
            bx, by, ex, ey = box
            bw, bh = ex - bx, ey - by
            if x < bx - 1 or y < by - 1 or x + rw > ex + 1 or y + rh > ey + 1:
                raise ValueError(f'clipped target {gid}:{step}: {box}')
            rect = [max(0, round(v * 100 / d, 4)) for v, d in zip((x-bx, y-by, rw, rh), (bw, bh, bw, bh))]
            out[f'{gid}:{step}'] = {'file': url, 'rect': rect}
    for old in DEST.glob('cut-*.png'):
        if old.name not in used:
            old.unlink()
    script = ("// Generated by scripts/render-guide-crops.py. Full illustrations remain authoritative.\n'use strict';\n"
              "(function(root, rows) { if (typeof module === 'object' && module.exports) module.exports = rows; "
              "else root.WorkbenchGuideCrops = rows; })(globalThis, " + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ');\n')
    (APP / 'guide-crops.js').write_bytes(script.encode())
    print(f'{len(out)} detail previews for {len(rows)} guide steps; {len(used)} generated crops')


if __name__ == '__main__':
    main()
