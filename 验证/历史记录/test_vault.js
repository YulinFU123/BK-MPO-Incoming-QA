const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {Vault,open}=require('../源码/vault');
const dir=path.join(__dirname,'vault-qa-'+Date.now());fs.mkdirSync(dir);
const state={version:1,templates:[{id:'incoming',name:'测试',columns:[{id:'silk',label:'底座丝印',type:'text'}]}],records:[{id:'r1',templateId:'incoming',createdAt:new Date().toISOString(),values:{silk:'0012',sn:'PRIVATE-QUALITY-RECORD-TEST'}}]};
const pass='QA-only-password-1',next='QA-only-password-2';
(async()=>{
const vault=new Vault(path.join(dir,'vault.json'));
await vault.setup(pass,state);
let disk=fs.readFileSync(vault.file,'utf8');
assert(!disk.includes('PRIVATE-QUALITY'));assert(!disk.includes(pass));assert(!Object.hasOwn(JSON.parse(disk),'records'));
const firstIV=JSON.parse(disk).iv;
vault.save(state);assert.notEqual(JSON.parse(fs.readFileSync(vault.file,'utf8')).iv,firstIV);
await assert.rejects(()=>vault.setup(pass,state));
const backup=vault.backup();vault.lock();assert.equal(vault.key,null);assert.equal(vault.data,null);
assert.throws(()=>vault.save(state));await assert.rejects(()=>vault.unlock('wrong-password'));
assert.equal((await vault.unlock(pass)).records[0].values.silk,'0012');
await assert.rejects(()=>vault.changePassword('wrong-password',next));
await vault.changePassword(pass,next);vault.lock();await assert.rejects(()=>vault.unlock(pass));
await vault.unlock(next);const decoded=await open(backup,pass);assert.equal(decoded.data.records[0].values.silk,'0012');decoded.key.fill(0);
disk=fs.readFileSync(vault.file,'utf8');
await assert.rejects(()=>vault.restore(backup,'wrong-password'));assert.equal(fs.readFileSync(vault.file,'utf8'),disk);
const corrupt=JSON.parse(backup);corrupt.data=(corrupt.data[0]==='A'?'B':'A')+corrupt.data.slice(1);
await assert.rejects(()=>vault.restore(JSON.stringify(corrupt),pass));assert.equal(fs.readFileSync(vault.file,'utf8'),disk);
await vault.restore(backup,pass);vault.lock();assert.equal((await vault.unlock(pass)).records[0].values.silk,'0012');
const originalWrite=vault.write;vault.write=()=>{throw Error('simulated disk full')};
await assert.rejects(()=>vault.changePassword(pass,next));vault.write=originalWrite;assert.equal((await vault.unlock(pass)).records.length,1);
console.log('PASS encryption, random IV, lock, wrong password, password change, backup restore, tamper rejection, failed-write preservation');
})().catch(e=>{console.error(e);process.exitCode=1});
